export function pickLocalizedName(
  item: { name_ar: string; name_fr: string; name_en: string } | null | undefined,
  locale: Locale
): string {
  if (!item) return '';
  if (locale === 'ar') return item.name_ar;
  if (locale === 'fr') return item.name_fr;
  return item.name_en;
}
